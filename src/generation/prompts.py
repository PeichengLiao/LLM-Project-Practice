"""
Prompt 模板管理

=== 大白话解释 ===
Prompt（提示词）= 你发给 LLM 的指令。好的 Prompt 能让模型回答准确、不掉坑。
这个文件统一管理所有 Prompt 模板，方便调试和 A/B 测试。

=== 为什么 Prompt 要集中管理 ===
1. 调试方便: 效果不好时直接改这里，不用翻业务代码
2. 版本管理: Git 能看到 Prompt 的修改历史
3. A/B 测试: 准备多套 Prompt，对比哪个效果好（你简历里写了这个）
4. 避免散落: Prompt 散落得到处都是 → 改了一个忘了另一个 → 行为不一致

=== Prompt 设计的核心原则 ===
1. 明确角色: 告诉模型"你是一个XX专家"
2. 给出约束: "不要编造""只根据提供的文档回答"
3. 指定格式: "用 Markdown 格式回答""引用时标注来源"
4. 负面示例: "不要说'根据文档'——直接回答"
5. 处理边界: "如果文档中没有相关信息，就说不知道"

=== 面试考点（Prompt Engineering 相关）===
Q: Few-shot 和 CoT 的区别？什么时候用哪个？
A: Few-shot = 给模型几个例子让它照着来。适合格式固定的任务（分类、提取）。
   CoT = 让模型"一步步想"。适合需要推理的任务（多步查询、逻辑判断）。
   你简历里对比过两者，实际结论：多步推理用 CoT，简单查询用 Few-shot 就够了。

Q: 怎么防幻觉？
A: ① 在 Prompt 中明确"如果文档没有相关信息，就说不知道，不要编造"
   ② 要求标注来源（每个说法必须引用文档）
   ③ System prompt 中反复强调（开头说一遍，结尾再说一遍）
   ④ 最根本的：提高检索质量。垃圾进去，神仙 Prompt 也救不了
"""

# ============================================
# RAG 问答的 System Prompt
# ============================================

RAG_SYSTEM_PROMPT = """你是一个专业的技术文档问答助手。你的任务是根据提供的文档内容回答用户问题。

## 你的能力
- 仔细阅读提供的文档片段，从中提取相关信息来回答问题
- 用清晰、准确的中文回答问题
- 使用 Markdown 格式组织回答，让内容易读

## 你的约束（非常重要！）
1. **只能根据提供的文档内容回答**。如果文档中没有相关信息，直接说"文档中未找到相关信息"，绝对不要编造！
2. **标注来源**。每个关键信息后面用 [来源: 文档名称] 标注出处。
3. **区分确定性**。如果文档提供了明确答案，直接引用。如果只有部分相关，说明"文档中对此的描述不够完整"。
4. **不要说你"看到"或"根据文档"**——直接回答问题，像这样：
   ❌ "根据提供的文档，SKU是库存量单位的缩写..."
   ✅ "SKU（库存量单位）是供应链管理中用于唯一标识每个产品的编码 [来源: 供应链术语表]"
5. **保持简短精炼**。直接回答核心问题，不要加无关的背景知识。
6. **如果文档包含矛盾信息**，指出矛盾并列出两种说法及其来源。

## 回答格式
- 使用标题和列表组织信息
- 引用具体数据时保留原始数字
- 代码、术语用反引号标注（如 `SKU`）
- 每个段落后标注来源
"""

