def build_rag_prompt(question: str, context: str, chat_history: list = None) -> list:
    """
    构建 RAG 对话的消息列表

    参数:
        question: 用户当前问题
        context: 检索到的文档文本（多个文档拼接在一起）
        chat_history: 之前的对话 [{"role": "user", "content": "..."}, ...]

    返回:
        [{"role": "system", "content": "..."}, {"role": "user", "content": "..."}]

    面试相关: messages 的结构 —— 为什么要把历史对话也传进去？
    因为 LLM 是无状态的，每次请求都是独立的。如果不传历史，
    它不知道你们刚才聊了什么。"继续""再详细点"这种追问就失效了。
    """
    messages = [
        {"role": "system", "content": RAG_SYSTEM_PROMPT},
    ]

    # 把历史对话也加进去（如果有的话）
    if chat_history:
        messages.extend(chat_history)

    # 当前问题 + 检索到的文档
    user_content = RAG_USER_TEMPLATE.format(
        context=context,
        question=question,
    )
    messages.append({"role": "user", "content": user_content})

    return messages


def format_context(search_results: list, max_chars: int = 4000) -> str:
    """
    将检索结果格式化为上下文字符串

    参数:
        search_results: [{"text": "...", "score": 0.85, "metadata": {...}}, ...]
        max_chars: 上下文最大字符数。太长了 LLM 的注意力会分散，
                   而且 DeepSeek API 按 token 收费，省着点用

    返回:
        格式化的上下文字符串

    设计决策: 相关性得分标注
    你简历里写了这个坑: "最初直接拼接文档，LLM容易被低相关文档带偏，
    加了相关性得分标注后改善"。这就是加得分标注的原因——
    让模型知道哪些文档更值得信任。
    """
    parts = []
    total_chars = 0

    for i, result in enumerate(search_results, 1):
        text = result["text"]
        score = result.get("score", 0)
        source = result.get("metadata", {}).get("source", result.get("metadata", {}).get("title", "未知来源"))

        # 截断过长的单条文本
        if len(text) + total_chars > max_chars:
            remaining = max_chars - total_chars
            if remaining < 200:  # 剩余太少就不塞了
                break
            text = text[:remaining] + "..."

        # 关键: 标注相关性得分，让模型知道该优先参考哪些文档
        # 你简历里的经验: 不标注得分 → 低相关文档"带偏"模型
        part = f"[文档{i}] 来源: {source} | 相关性: {score:.2%}\n{text}"
        parts.append(part)
        total_chars += len(text)

    return "\n\n---\n\n".join(parts)
